export function getDealInterestMail(deal) {
  return {
    email: DEAL_BOARD_EMAIL,
    subject: `Deal Board Interest: ${deal.id}: ${deal.title}`,
    body: [
      `Hello YD Advisory,`,
      ``,
      `I am writing to register interest in the following Deal Board mandate:`,
      ``,
      `Deal ID: ${deal.id}`,
      `Title: ${deal.title}`,
      `Category: ${deal.category}`,
      `Sector: ${deal.sector}`,
      `Geography: ${deal.geography}`,
      `Indicative size: ${deal.size}`,
      ``,
      `Please share the next steps and any NDA / information package required.`,
      ``,
      `I will attach my pitch deck / relevant materials to this email.`,
      ``,
      `Name:`,
      `Organisation:`,
      `Role:`,
      `Phone:`,
      ``,
      `Thank you,`,
    ].join('\n'),
  };
}

